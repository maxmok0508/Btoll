    static var isEnglish: Bool {
        let selected=UserDefaults.standard.string(forKey:"btollInterfaceLanguage") ?? "system"
        if selected=="en" { return true }
        if selected=="zh-Hans" { return false }
        return !(Bundle.main.preferredLocalizations.first ?? Locale.preferredLanguages.first ?? "en").hasPrefix("zh")
    }
    static func text(_ value:String)->String {
        guard isEnglish else { return value }
        if let translated=english[value] { return translated }
        if let match=value.range(of:#"^(工作|待命|响应|完成|阻塞|旋转|标志|展示|动作) [A-F]$"#,options:.regularExpression) {
            let parts=String(value[match]).split(separator:" ")
            let names=["工作":"Working","待命":"Idle","响应":"Responding","完成":"Done","阻塞":"Blocked","旋转":"Rotation","标志":"Logo","展示":"Showcase","动作":"Motion"]
            return (names[String(parts[0])] ?? String(parts[0]))+" "+String(parts[1])
        }
        var result=value
        let phrases:[(String,String)]=[
            ("个会话工作中","active sessions"),("个状态待确认","uncertain sessions"),("个逻辑核心","logical cores"),
