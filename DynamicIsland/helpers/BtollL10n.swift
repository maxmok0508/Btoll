        for (source,target) in phrases.sorted(by:{$0.0.count>$1.0.count}) { result=result.replacingOccurrences(of:source,with:target) }
        return result.replacingOccurrences(of:"1 active sessions",with:"1 active session").replacingOccurrences(of:"1 uncertain sessions",with:"1 uncertain session")
    }
    static func writeBridgeLanguage() {
        let root=FileManager.default.homeDirectoryForCurrentUser.appendingPathComponent("Library/Application Support/AtollCodexBridge")
        try? FileManager.default.createDirectory(at:root,withIntermediateDirectories:true)
        if let data=try? JSONSerialization.data(withJSONObject:["language":isEnglish ? "en":"zh"]) { try? data.write(to:root.appendingPathComponent("interface-preferences.json"),options:.atomic) }
    }
